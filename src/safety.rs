use sha2::{Digest, Sha256};
use std::path::Path;

pub const HASH_FILE_NAME: &str = ".brainhash";

#[derive(Debug, PartialEq, Eq)]
pub enum SafetyStatus {
    SafeToCreate,
    SafeToOverwrite,
    LocallyModified(String), // The skill was previously generated by Brain, but someone edited SKILL.md manually!
    ForeignConflict,         // Never had a .brainhash, foreign hand-written skill
}

pub fn check_file_safety(path: &Path) -> Result<SafetyStatus, std::io::Error> {
    if !path.exists() {
        return Ok(SafetyStatus::SafeToCreate);
    }

    let current_content = std::fs::read_to_string(path)?;

    // Check if companion .brainhash file exists in the same folder
    if let Some(parent) = path.parent() {
        let hash_file = parent.join(HASH_FILE_NAME);
        if hash_file.exists() {
            let hash_content = std::fs::read_to_string(&hash_file)?;
            if let Some(expected_line) = hash_content.lines().find(|l| l.starts_with("sha256:")) {
                let expected_hash = expected_line.trim_start_matches("sha256:").trim();
                let actual_hash = hex::encode(&Sha256::digest(current_content.as_bytes())[..8]);

                if expected_hash == actual_hash {
                    return Ok(SafetyStatus::SafeToOverwrite);
                } else {
                    return Ok(SafetyStatus::LocallyModified(path.display().to_string()));
                }
            }
        }
    }

    // No .brainhash found -> this is a foreign or unmanaged skill
    Ok(SafetyStatus::ForeignConflict)
}
